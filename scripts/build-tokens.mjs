// Turns design/tokens/*.tokens.json into src/styles/tokens.css so the site
// and the design system never drift. Runs before `dev` and `build`.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = async (path) => JSON.parse(await readFile(new URL(path, root), 'utf8'));

const base = await read('design/tokens/ryvanse.tokens.json');
const derived = await read('design/tokens/ry-bealey.tokens.json');

const primitives = Object.fromEntries(base.color.tokens.map((t) => [t.name, t.value]));
const resolve = (value) =>
  value.replace(/\{([a-z-]+)\}/g, (_, name) => {
    if (!(name in primitives)) throw new Error(`Unknown Ryvanse color "${name}"`);
    return `var(--rv-${name})`;
  });

const decl = (name, value) => `  --${name}: ${value};`;
const lines = [];

lines.push(...base.color.tokens.map((t) => decl(`rv-${t.name}`, t.value)));
for (const [name, stack] of Object.entries(base.type.families)) lines.push(decl(`font-${name}`, stack));

const styleDecls = (s, family) => [
  decl(`type-${s.name}-family`, `var(--font-${family})`),
  decl(`type-${s.name}-size`, s.fontSize),
  decl(`type-${s.name}-line`, s.lineHeight),
  decl(`type-${s.name}-weight`, String(s.fontWeight)),
  ...(s.letterSpacing ? [decl(`type-${s.name}-tracking`, s.letterSpacing)] : []),
];
for (const group of base.type.groups) for (const s of group.styles) lines.push(...styleDecls(s, group.family));
for (const group of derived.type.groups) for (const s of group.styles) lines.push(...styleDecls(s, s.family));

for (const t of base.spacing.tokens) lines.push(decl(t.name, t.value));
for (const t of base.radius.tokens) lines.push(decl(t.name, t.value));

const themed = (theme) => derived.color.tokens.map((t) => decl(`color-${t.name}`, resolve(t.value[theme])));

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens. Do not edit. */
@layer tokens {
:root {
${lines.join('\n')}
}
:root, .theme-dark {
${themed('dark').join('\n')}
  color-scheme: dark;
}
:root[data-theme='light'] {
${themed('light').join('\n')}
  color-scheme: light;
}
}
`;

await writeFile(new URL('src/styles/tokens.css', root), css);
console.log(`tokens: wrote ${lines.length + derived.color.tokens.length * 2} custom properties`);
